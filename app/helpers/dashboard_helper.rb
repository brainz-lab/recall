  def icon(name)
    ICONS[name.to_sym]&.html_safe
  end

  # Navigation helpers for sidebar
  def nav_active?(path_pattern)
    case path_pattern
    when "/logs"
      controller_name == "logs"
    when "/analytics"
      action_name == "analytics"
    when "/setup"
      action_name == "setup"
    when "/mcp"
      action_name == "mcp_setup"
    when "/settings"
      action_name == "edit"
    else
      request.path.include?(path_pattern)
    end
  end

  def nav_link_class(path_pattern)
    nav_active?(path_pattern) ? "nav-item active" : "nav-item"
  end
